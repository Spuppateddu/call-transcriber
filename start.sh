#!/usr/bin/env bash
#
# call-transcriber — record a conversation
#
# Records your MICROPHONE and your PC AUDIO (the other participants of a call,
# or whatever else your PC plays) as two separate tracks. Recording itself is
# very light on the CPU, so the call is not affected. When you stop with Ctrl+C,
# both tracks are transcribed with whisper.cpp and merged into a single
# transcript.txt, time-ordered, with [ME] / [THEM] speaker labels.
#
# Files land in ./sessions/<timestamp>/
#
# While recording, a DRAFT transcript scrolls in the terminal ~30 seconds
# behind live (handy to catch a name or a number), done with a fast model on
# half the cores at low priority, so the call always gets the CPU first. On a
# machine too slow to keep up it skips audio rather than falling behind — the
# accurate transcript produced at the end still covers all of it.
#
# When you run it the script ASKS for the common options (devices, language,
# model, live draft) with all the valid answers listed — no need to remember
# anything. You can still preset any option as an environment variable to skip
# its question (handy for scripting or a fixed setup):
#   MIC_SRC=...         PipeWire source to record as the microphone
#   PC_SRC=...          PipeWire source to record as the PC audio (a .monitor)
#   LANG_CODE=en        spoken language (default: auto-detect)
#   MODEL=small         whisper model for the transcription at the end
#   AUTO_TRANSCRIBE=0   record only; transcribe later with ./transcribe.sh
#   LIVE=0              disable the live draft in the terminal
#   LIVE_MODEL=base     model for the live draft (default: base on a CPU build,
#                       the best of medium/small/base on a CUDA build)
#   LIVE_CHUNK=30       seconds of audio per live chunk
#
# List the device names with:  pactl list short sources
#
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/lib.sh"
WHISPER_DIR="$HERE/whisper.cpp"
AUTO_TRANSCRIBE="${AUTO_TRANSCRIBE:-1}"

# pgrep is what kill_tree walks the process tree with: without it, stopping the
# live draft would only signal its shell and leave the whisper run underneath it
# going, so it is a hard requirement rather than a nicety.
for cmd in pactl parec ffmpeg pgrep; do
    command -v "$cmd" >/dev/null 2>&1 || {
        echo "ERROR: '$cmd' not found. Run ./install.sh first." >&2; exit 1; }
done

# --- interactive setup -------------------------------------------------------
# Ask the common options here so you never have to remember any argument.
# A question is skipped if that option is already set — either passed on the
# command line (e.g. MODEL=medium ./start.sh) or remembered in config.env from
# a previous run. With no terminal available, the defaults below are used.
MODELS_DIR="$WHISPER_DIR/models"
CONFIG_FILE="$HERE/config.env"

# Remember what was set on the command line BEFORE loading the saved file, so a
# command-line value keeps winning even if you later choose to change the setup.
CLI_MIC_SRC="${MIC_SRC:-}"
CLI_PC_SRC="${PC_SRC:-}"
CLI_LANG_CODE="${LANG_CODE:-}"
CLI_MODEL="${MODEL:-}"
CLI_LIVE="${LIVE:-}"

# True if a file is ours and carries no group/other bits at all — i.e. only we
# can write it. Sourcing a file runs whatever is in it, so write access to
# config.env is write access to this shell, and config.env is the one file here
# that travels: it gets copied between machines, restored from a backup, or
# generated by hand, any of which can land it with the wrong mode.
# This is NOT a defense against a writable checkout. If someone can write in
# this directory they can equally rewrite lib.sh, which we source a few lines
# up without asking anything — keep the checkout itself private.
config_is_private() {  # $1 = file
    local owner mode
    owner="$(stat -c %u "$1" 2>/dev/null)" || return 1
    mode="$(stat -c %a "$1" 2>/dev/null)" || return 1
    [ "$owner" = "$(id -u)" ] || return 1
    case "$mode" in
        *00) return 0 ;;   # nothing granted to group or other
        *)   return 1 ;;
    esac
}

# Load remembered answers (config.env uses ':=' so it fills only what you did
# not set on the command line). A syntax error in a sourced file would kill this
# script outright, so the file is parsed first and ignored if it is broken.
# To be clear about what that check is worth: `bash -n` validates SYNTAX only.
# It says the file is shell, never that the shell in it is harmless — the
# ownership check above is what decides whether we trust it at all.
CONFIG_LOADED=0
if [ -f "$CONFIG_FILE" ]; then
    if ! config_is_private "$CONFIG_FILE"; then
        echo "WARNING: $CONFIG_FILE is not private — ignoring it." >&2
        echo "         Sourcing it would run its contents as you, so it must be" >&2
        echo "         owned by you and readable/writable by nobody else." >&2
        echo "         Fix it with:  chmod 600 '$CONFIG_FILE'" >&2
        echo "         (or delete it to reconfigure:  rm '$CONFIG_FILE')" >&2
    elif bash -n "$CONFIG_FILE" 2>/dev/null; then
        . "$CONFIG_FILE"
        CONFIG_LOADED=1
    else
        echo "WARNING: $CONFIG_FILE is not valid shell — ignoring it." >&2
        echo "         Delete it to reconfigure:  rm '$CONFIG_FILE'" >&2
    fi
fi

ask() {  # $1 = prompt shown on screen; echoes the typed reply on stdout
    local reply=""
    read -rp "$1" reply </dev/tty || reply=""
    printf '%s' "$reply"
}

ASKED=()          # options we prompted for this run (offered for saving)
HEADER_SHOWN=0
maybe_header() {
    [ "$HEADER_SHOWN" = "1" ] && return
    echo "=== Recording setup — press Enter to accept the [default] ==="
    HEADER_SHOWN=1
}

# --- audio devices -----------------------------------------------------------
# PipeWire calls every recordable thing a "source". Real inputs (mic, line-in,
# webcam mic) are plain sources; what the PC plays back — i.e. the voices of
# the other participants — is recorded from the ".monitor" source of an output.
# So: microphone = a non-monitor source, PC audio = a monitor source.
# `pactl list sources` is a subprocess whose answer does not change while we
# set up, so read it once and filter the cached text on every later lookup.
# LC_ALL=C is mandatory, not tidiness: pactl is translated, so with an Italian
# or German language pack installed the field names below become 'Nome:' /
# 'Descrizione:', every source parses as nothing, and the device questions
# silently disappear — which is the exact mistake this menu exists to prevent.
PACTL_SOURCES=""
load_sources() {
    [ -n "$PACTL_SOURCES" ] && return 0
    PACTL_SOURCES="$(LC_ALL=C pactl list sources 2>/dev/null || true)"
    return 0
}

list_sources() {  # $1 = mic|pc|all  ->  lines "name<TAB>human description"
    load_sources
    printf '%s\n' "$PACTL_SOURCES" | awk -v kind="$1" '
        /^[[:space:]]*Name:/ {
            name = $0; sub(/^[[:space:]]*Name:[[:space:]]*/, "", name); next
        }
        /^[[:space:]]*Description:/ {
            if (name == "") next
            desc = $0; sub(/^[[:space:]]*Description:[[:space:]]*/, "", desc)
            is_monitor = (name ~ /\.monitor$/)
            if (kind == "all" || (kind == "pc") == is_monitor) print name "\t" desc
            name = ""
        }
    '
}

# Echo a source's human description; fail if that source is not connected.
# Both "what is this device called?" and "is this device still here?" are this
# one lookup, so they can never answer differently.
find_device() {  # $1 = source name
    local n d
    while IFS=$'\t' read -r n d; do
        [ "$n" = "$1" ] && { printf '%s' "$d"; return 0; }
    done < <(list_sources all)
    return 1
}

# For display: the description, falling back to the raw name when unknown.
describe_device() {  # $1 = source name
    find_device "$1" || printf '%s' "$1"
}

# Numbered menu of the available devices; sets CHOSEN to the picked source name.
CHOSEN=""
choose_device() {  # $1 = mic|pc   $2 = title   $3 = name to offer as default
    local kind="$1" title="$2" def="$3"
    local names=() descs=() n d i c mark def_i=0 found=0
    while IFS=$'\t' read -r n d; do names+=("$n"); descs+=("$d"); done \
        < <(list_sources "$kind")

    # No device parsed out of pactl. Falling back to the system default is all
    # we can do, but say so: a silent fallback here is how you end up recording
    # three hours on the webcam mic without ever being asked.
    if [ "${#names[@]}" -eq 0 ]; then
        echo "WARNING: could not list any $kind device from pactl — using the" >&2
        echo "         system default: ${def:-<none>}" >&2
        echo "         Check it with:  pactl list short sources" >&2
        CHOSEN="$def"
        return
    fi
    for i in "${!names[@]}"; do
        [ "${names[$i]}" = "$def" ] && { def_i=$i; found=1; }
    done
    # The system default can be missing here (e.g. it is a monitor while we are
    # listing microphones): offer the first device instead of something absent.
    [ "$found" = "1" ] || def="${names[0]}"

    maybe_header
    echo
    echo "$title"
    for i in "${!names[@]}"; do
        mark=""; [ "${names[$i]}" = "$def" ] && mark="   (default, current system choice)"
        echo "   $((i+1))) ${descs[$i]}$mark"
        echo "        ${names[$i]}"
    done
    c="$(ask "Choice [$((def_i+1))]: ")"
    c="$(pick_index "$c" "${#names[@]}" "$((def_i+1))")"
    CHOSEN="${names[$((c-1))]}"
}

# Fill the cache HERE, in the main shell. The lookups below read it through a
# process substitution, and a subshell filling it would only cache for itself.
load_sources

# What the system would use if we did not ask: default input, and the monitor
# of the default output.
DEFAULT_MIC="$(LC_ALL=C pactl get-default-source 2>/dev/null || true)"
DEFAULT_SINK="$(LC_ALL=C pactl get-default-sink 2>/dev/null || true)"
DEFAULT_PC=""
[ -n "$DEFAULT_SINK" ] && DEFAULT_PC="$DEFAULT_SINK.monitor"
# A remembered device disappears when you unplug the USB mic or the headset;
# forget it in that case so we ask again instead of recording nothing. Remember
# that we did: the setup summary below would otherwise print the system default
# in its place, quietly contradicting the warning we just gave.
MIC_DROPPED=0
PC_DROPPED=0
for v in MIC_SRC PC_SRC; do
    [ -n "${!v:-}" ] || continue
    find_device "${!v}" >/dev/null && continue
    echo "WARNING: the saved $v device is not connected right now:" >&2
    echo "         ${!v}" >&2
    unset "$v"
    printf -v "${v%_SRC}_DROPPED" '%d' 1
done

# If a saved setup was loaded, show it and let you keep or change it before
# recording. Choosing to change just forgets the saved values (keeping any
# command-line override) so the questions below run again.
if [ "$CONFIG_LOADED" = "1" ] && [ -e /dev/tty ]; then
    # A device dropped just above is shown as what we will fall back to, plus
    # why it is not the one you saved.
    setup_device_line() {  # $1 = label  $2 = device name  $3 = 1 if dropped
        local note="" shown="<none>"
        [ "$3" = "1" ] && note="   (saved device not connected — asking again)"
        [ -n "$2" ] && shown="$(describe_device "$2")"
        printf '      %-11s %s%s\n' "$1" "$shown" "$note"
    }
    echo "==> Current saved setup (config.env):"
    setup_device_line "Microphone:" "${MIC_SRC:-$DEFAULT_MIC}" "$MIC_DROPPED"
    setup_device_line "PC audio:"   "${PC_SRC:-$DEFAULT_PC}"   "$PC_DROPPED"
    echo "      Language:   ${LANG_CODE:-auto}"
    echo "      Model:      ${MODEL:-<best installed>}"
    echo "      Live draft: $([ "${LIVE:-1}" = "0" ] && echo off || echo on)"
    keep="$(ask 'Use this setup? [Y = keep / n = change it]: ')"
    case "$keep" in
        n|N|no|NO)
            MIC_SRC="$CLI_MIC_SRC"
            PC_SRC="$CLI_PC_SRC"
            LANG_CODE="$CLI_LANG_CODE"
            MODEL="$CLI_MODEL"
            LIVE="$CLI_LIVE"
            ;;
    esac
    echo
fi

if [ -e /dev/tty ]; then
    # 1) Which microphone to record as the [ME] track. The system default is
    #    often the wrong one (a webcam mic, for instance), hence this question.
    if [ -z "${MIC_SRC:-}" ]; then
        choose_device mic \
            "Microphone to record as [ME] — your own voice:" "$DEFAULT_MIC"
        MIC_SRC="$CHOSEN"
        ASKED+=("MIC_SRC")
    fi

    # 2) Which output to listen in on for the [THEM] track (the other people).
    #    It must be the output their voices actually play from: if you listen
    #    on headphones, pick the headphones' monitor, not the speakers'.
    if [ -z "${PC_SRC:-}" ]; then
        choose_device pc \
            "PC audio to record as [THEM] — the other people on the call.
Pick the output you actually LISTEN through (headset, speakers...):" \
            "$DEFAULT_PC"
        PC_SRC="$CHOSEN"
        ASKED+=("PC_SRC")
    fi

    # 3) Language spoken (used for both the draft and the final text).
    if [ -z "${LANG_CODE:-}" ]; then
        maybe_header
        echo
        echo "Language spoken in the recording:"
        echo "   1) auto - let whisper detect it automatically   (default)"
        echo "   2) en   - English"
        echo "   3) it   - Italian"
        echo "   ...or type any 2-letter code (es, fr, de, pt, ...)"
        echo "   Naming the language is a bit more reliable than auto-detect."
        c="$(ask 'Choice [1]: ')"
        case "$c" in
            ""|1) LANG_CODE="auto" ;;
            2)    LANG_CODE="en" ;;
            3)    LANG_CODE="it" ;;
            [a-z][a-z]) LANG_CODE="$c" ;;
            *)    echo "    Not a 2-letter language code — using auto-detect." >&2
                  LANG_CODE="auto" ;;
        esac
        ASKED+=("LANG_CODE")
    fi

    # 4) Model for the FINAL transcript — list only models actually installed,
    #    so you can never pick one that isn't there. Default = the best one.
    if [ -z "${MODEL:-}" ]; then
        # Through model_file, so where a model lives is spelled out in lib.sh
        # only — this menu cannot end up disagreeing with the code that loads it.
        installed=()
        for m in $MODEL_SIZES; do
            model_file "$WHISPER_DIR" "$m" >/dev/null && installed+=("$m")
        done
        if [ "${#installed[@]}" -gt 1 ]; then
            # Exactly the model transcribe.sh would pick on its own, so the
            # default here and its fallback can never disagree (lib.sh).
            default="$(best_model "$WHISPER_DIR")"
            maybe_header
            echo
            echo "Model for the final (accurate) transcript — bigger = better but slower:"
            i=1
            for m in "${installed[@]}"; do
                mark=""
                [ "$m" = "$default" ] && mark="   (default, best balance you have)"
                [ "$m" = "large-v3" ] && mark="$mark   [can take longer than the call]"
                echo "   $i) $m$mark"
                i=$((i+1))
            done
            echo "   (install more models with ./install.sh)"
            def_i=1
            for i in "${!installed[@]}"; do
                [ "${installed[$i]}" = "$default" ] && def_i=$((i+1))
            done
            c="$(ask "Choice [$default]: ")"
            c="$(pick_index "$c" "${#installed[@]}" "$def_i")"
            MODEL="${installed[$((c-1))]}"
            ASKED+=("MODEL")
        fi
        # 0 or 1 model installed: nothing to choose; transcribe.sh auto-picks it.
    fi

    # 5) Live draft transcript on screen while you talk?
    if [ -z "${LIVE:-}" ]; then
        maybe_header
        echo
        echo "Show the live draft transcript on screen while recording?"
        echo "   1) yes - rough but very handy to catch a name or a number (default)"
        echo "   2) no  - just show the recording timer"
        c="$(ask 'Choice [1]: ')"
        case "$c" in
            2) LIVE="0" ;;
            *) LIVE="1" ;;
        esac
        ASKED+=("LIVE")
    fi

    [ "$HEADER_SHOWN" = "1" ] && echo
fi

# Apply defaults for anything still unset (e.g. no terminal), and export the
# choices so the live.sh / transcribe.sh helpers inherit them.
MIC_SRC="${MIC_SRC:-$DEFAULT_MIC}"
PC_SRC="${PC_SRC:-$DEFAULT_PC}"
LANG_CODE="${LANG_CODE:-auto}"
LIVE="${LIVE:-1}"
# live.sh is a separate process, so it reads all of these from the ENVIRONMENT.
# A 'LIVE_CHUNK=20 ./start.sh' prefix exports for free, which is why the live
# options appeared to work; set the same thing in config.env and it is sourced
# into a plain shell variable that stops at this fork. Exporting a variable
# nobody set is a no-op, so live.sh still applies its own defaults for those.
export LANG_CODE LIVE LIVE_CHUNK LIVE_MODEL LIVE_THREADS

# Offer to remember the answers so future runs skip the questions entirely.
if [ -e /dev/tty ] && [ "${#ASKED[@]}" -gt 0 ]; then
    save="$(ask 'Remember these answers so I stop asking next time? [y/N]: ')"
    case "$save" in
        y|Y|yes|YES)
            # %q quotes each value for the shell that will source this file back:
            # without it a quote in an answer breaks every future run, and a
            # '$(...)' in a device name would execute as a command.
            # Created 0600 *before* anything is written: start.sh sources this
            # file, so write access to it is write access to your shell.
            : > "$CONFIG_FILE"
            chmod 600 "$CONFIG_FILE"
            {
                echo "# call-transcriber — saved defaults (written by start.sh)."
                echo "# Delete a line to be asked about that option again;"
                echo "# delete the whole file to reconfigure from scratch."
                echo "# A value passed on the command line still overrides these."
                printf ': ${MIC_SRC:=%q}\n'   "$MIC_SRC"
                printf ': ${PC_SRC:=%q}\n'    "$PC_SRC"
                printf ': ${LANG_CODE:=%q}\n' "$LANG_CODE"
                [ -n "${MODEL:-}" ] && printf ': ${MODEL:=%q}\n' "$MODEL"
                printf ': ${LIVE:=%q}\n'      "$LIVE"
            } > "$CONFIG_FILE"
            echo "==> Saved to config.env — you won't be asked again."
            echo
            ;;
    esac
fi

# --- sanity-check the devices ------------------------------------------------
# They come from the questions above (or from config.env / the environment).
if [ -z "$MIC_SRC" ] || [ -z "$PC_SRC" ]; then
    echo "ERROR: no audio device to record from. Check Settings -> Sound," >&2
    echo "       or list the names with: pactl list short sources" >&2
    exit 1
fi
case "$MIC_SRC:$PC_SRC" in
    *auto_null*)
        echo "WARNING: PipeWire reports no real audio device ('auto_null')." >&2
        echo "         Check Settings -> Sound. Recording will likely be silent." >&2 ;;
esac
case "$MIC_SRC" in
    *.monitor)
        echo "WARNING: the microphone track is set to a monitor, not a real mic." >&2 ;;
esac
case "$PC_SRC" in
    *.monitor) ;;
    *) echo "WARNING: the PC-audio track is not a '.monitor' source — it will" >&2
       echo "         record an input, not what your PC plays." >&2 ;;
esac

# --- sanity-check the model --------------------------------------------------
# A MODEL from config.env or the command line can name one that has since been
# deleted. Resolve it NOW: discovering it only when transcribing would mean
# sitting through the whole call before finding out. Done after the save prompt
# above so an auto-picked model is never written into config.env as a choice.
if [ -n "${MODEL:-}" ] && ! model_file "$WHISPER_DIR" "$MODEL" >/dev/null; then
    echo "WARNING: the requested model '$MODEL' is not installed." >&2
    echo "         Expected: $MODELS_DIR/ggml-$MODEL.bin" >&2
    echo "         Get it back with:  MODEL=$MODEL ./install.sh" >&2
    MODEL=""
fi
if [ -z "${MODEL:-}" ]; then
    MODEL="$(best_model "$WHISPER_DIR")" || {
        echo "ERROR: no whisper model installed — nothing could transcribe this" >&2
        echo "       recording. Run ./install.sh first." >&2
        exit 1
    }
    echo "==> Model for the final transcript: $MODEL"
fi
export MODEL

# --- output location ---------------------------------------------------------
STAMP="$(date +%Y-%m-%d_%H-%M-%S)"
OUT_DIR="$HERE/sessions/$STAMP"
# 0700/0600 for everything in here: these are recordings and transcripts of
# private calls, and the repo does not have to live under a private $HOME.
# Set for the rest of the run, so the .raw/.wav/.srt/.txt written from here on
# — and by the transcribe.sh we exec into — are private too.
umask 077
mkdir -p "$OUT_DIR"
chmod 700 "$HERE/sessions"
MIC_RAW="$OUT_DIR/mic.raw"
PC_RAW="$OUT_DIR/pc.raw"
MIC_WAV="$OUT_DIR/mic.wav"
PC_WAV="$OUT_DIR/pc.wav"

echo "==> Session:      $OUT_DIR"
echo "    Microphone:   $(describe_device "$MIC_SRC")"
echo "                  $MIC_SRC"
echo "    PC audio:     $(describe_device "$PC_SRC")"
echo "                  $PC_SRC"

# --- record ------------------------------------------------------------------
# Raw PCM (no header): safe to cut at any moment, converted to .wav afterwards.
parec -d "$MIC_SRC" --rate="$RATE" --channels=1 --format=s16le > "$MIC_RAW" &
MIC_PID=$!
parec -d "$PC_SRC" --rate="$RATE" --channels=1 --format=s16le > "$PC_RAW" &
PC_PID=$!

STOP=""
LIVE_PID=""
cleanup_children() {
    kill "$MIC_PID" "$PC_PID" 2>/dev/null || true
    [ -n "${LIVE_PID:-}" ] && kill_tree TERM "$LIVE_PID"
    return 0
}

# A hangup means the terminal went away — window closed, ssh dropped. Stop as
# if it were Ctrl+C, but point our output at a file first: writing to a pty
# whose terminal is gone fails with EIO, and under 'set -e' that would abort
# the raw->wav conversion below, losing exactly what this trap exists to save.
on_hangup() {
    exec >>"$OUT_DIR/session.log" 2>&1
    STOP=1
}

# Installed here, before anything that can block. The live-draft wait below can
# sit for ten seconds, and until these exist a TERM or a HUP takes this script
# down while both recorders keep writing to the .raw files with nothing left
# that would ever stop them.
trap 'STOP=1' INT TERM
trap on_hangup HUP
trap cleanup_children EXIT

# Live draft: a helper process transcribes the tracks in near-real-time with
# a fast model and prints the lines here. If it can't start (no fast model),
# it says why and recording simply continues without it.
if [ "$LIVE" = "1" ]; then
    LIVE_LOG="$OUT_DIR/live.log"
    "$HERE/live.sh" "$OUT_DIR" 2>"$LIVE_LOG" &
    LIVE_PID=$!
    # live.sh creates live.txt once it has a model and is ready; if it bailed
    # out instead, say so here rather than promising a draft that never comes.
    # Wait on the process rather than on a fixed deadline: getting ready can
    # take a moment (a CUDA build is slow to inspect), and a deadline short
    # enough to report a failure promptly is also short enough to call a working
    # draft missing. Dying is what we are actually waiting to rule out, so
    # watch for that instead — it also makes the failure case return at once.
    for _ in $(seq 50); do
        [ -f "$OUT_DIR/live.txt" ] && break
        kill -0 "$LIVE_PID" 2>/dev/null || break
        sleep 0.2
    done
    if [ -f "$OUT_DIR/live.txt" ]; then
        echo "==> Live draft: on screen ~${LIVE_CHUNK:-$LIVE_CHUNK_DEFAULT}s behind (also saved to live.txt). LIVE=0 disables it."
    else
        echo "==> Live draft: NOT available — recording continues without it." >&2
        [ -s "$LIVE_LOG" ] && sed 's/^/    /' "$LIVE_LOG" >&2
    fi
fi

echo
echo "==> RECORDING — go ahead and talk. Press Ctrl+C to stop and transcribe."
START_TS="$(date +%s)"
while [ -z "$STOP" ]; do
    sleep 1 || true
    # On Ctrl+C the recorders die together with us — that's a normal stop,
    # so check STOP again before diagnosing a dead recorder.
    [ -n "$STOP" ] && break
    if ! kill -0 "$MIC_PID" 2>/dev/null || ! kill -0 "$PC_PID" 2>/dev/null; then
        echo
        echo "WARNING: a recorder died (device unplugged?). Stopping." >&2
        break
    fi
    ELAPSED=$(( $(date +%s) - START_TS ))
    printf '\r    Recording... %02d:%02d:%02d ' \
        $((ELAPSED/3600)) $((ELAPSED%3600/60)) $((ELAPSED%60))
done
echo
echo "==> Stopping recorders..."
# Stop the live draft first: it reads the .raw files we are about to delete.
# Signalling live.sh alone only sets its STOP flag — it cannot act on it until
# the whisper run it is waiting on returns, which is up to a whole chunk of
# audio. kill_tree takes that whisper down too, so stopping is immediate.
if [ -n "$LIVE_PID" ]; then
    kill_tree TERM "$LIVE_PID"
    for _ in $(seq 20); do
        kill -0 "$LIVE_PID" 2>/dev/null || break
        sleep 0.1
    done
    kill_tree KILL "$LIVE_PID"
    wait "$LIVE_PID" 2>/dev/null || true
fi
kill "$MIC_PID" "$PC_PID" 2>/dev/null || true
wait "$MIC_PID" 2>/dev/null || true
wait "$PC_PID" 2>/dev/null || true
trap - EXIT INT TERM HUP

# --- raw -> wav ---------------------------------------------------------------
CONVERT_FAILED=0
for raw in "$MIC_RAW" "$PC_RAW"; do
    wav="${raw%.raw}.wav"
    if [ -s "$raw" ]; then
        # On failure (a full disk is the realistic one) do NOT delete the .raw
        # and do NOT abort: the audio is all there, it just has no header yet.
        # Keep going so the other track still converts, and print the exact
        # command to finish the job — nothing downstream reads .raw files.
        if ffmpeg -hide_banner -loglevel error -y \
                -f s16le -ar "$RATE" -ac 1 -i "$raw" "$wav"; then
            rm -f "$raw"
        else
            CONVERT_FAILED=1
            rm -f "$wav"
            echo "ERROR: could not convert $(basename "$raw") to .wav (disk full?)." >&2
            echo "       Your audio is NOT lost — it is still in:" >&2
            echo "         $raw" >&2
            echo "       Free some space, then finish it by hand with:" >&2
            echo "         ffmpeg -f s16le -ar $RATE -ac 1 -i '$raw' '$wav'" >&2
            echo "       and transcribe with:  ./transcribe.sh '$OUT_DIR'" >&2
        fi
    else
        echo "WARNING: $(basename "$raw") is empty — that track recorded nothing." >&2
        rm -f "$raw"
    fi
done

# Warn if a track is (almost) silent — usually a wrong default device.
check_level() {
    local wav="$1" name="$2" mean=""
    [ -f "$wav" ] || return 0
    mean="$(mean_volume "$wav")" || return 0
    if db_below "$mean" "$SILENCE_DB"; then
        echo "WARNING: the $name track sounds silent (mean volume ${mean} dB)." >&2
        echo "         Wrong device? Run ./start.sh again and pick another one" >&2
        echo "         (answer 'n' at the saved-setup question)." >&2
    fi
}
check_level "$MIC_WAV" "microphone"
check_level "$PC_WAV" "PC-audio"

echo "==> Recording saved:"
[ -f "$MIC_WAV" ] && echo "    $MIC_WAV"
[ -f "$PC_WAV" ] && echo "    $PC_WAV"

# --- transcribe ----------------------------------------------------------------
# A track that failed to convert is still sitting there as .raw. Transcribing
# now would quietly produce a one-sided transcript and look like it worked, so
# stop instead and leave the recovery instructions printed above as the last word.
if [ "$CONVERT_FAILED" = "1" ]; then
    echo
    echo "==> Not transcribing: a track is still .raw (see the ERROR above)." >&2
    exit 1
fi
if [ "$AUTO_TRANSCRIBE" = "1" ]; then
    echo
    exec "$HERE/transcribe.sh" "$OUT_DIR"
else
    echo
    echo "Transcribe later with:  ./transcribe.sh sessions/$STAMP"
fi
